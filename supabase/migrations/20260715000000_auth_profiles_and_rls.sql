create table public.fixed_product_quantity_ranges (
  id uuid primary key,
  fixed_product_id uuid not null references public.fixed_products(id) on delete cascade,
  min_quantity integer not null check (min_quantity >= 1),
  max_quantity integer not null check (max_quantity >= min_quantity),
  unit_price numeric(12, 2) not null,
  created_at timestamptz not null default timezone('utc', now()),
  unique (fixed_product_id, min_quantity, max_quantity)
);

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'users', 'legacy_user_migrations', 'clients', 'papers', 'finishes', 'base_measurements', 'paper_pricing',
    'finish_pricing', 'quotes', 'quote_items', 'quote_item_finishes', 'fixed_products',
    'fixed_product_quantity_ranges'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
  end loop;
end;
$$;
