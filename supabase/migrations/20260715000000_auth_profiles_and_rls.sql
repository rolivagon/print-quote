-- Supabase is the schema authority. Browser roles receive no public-table policies;
-- FastAPI connects with its backend database credential and performs authorization itself.

create type public.userrole as enum ('SUPER_ADMIN', 'ADMIN', 'VENDEDOR');
create type public.clienttype as enum ('INDIVIDUAL', 'COMPANY');
create type public.quotestatus as enum ('DRAFT', 'SENT', 'APPROVED', 'REJECTED');
create type public.printtype as enum ('DIGITAL', 'OFFSET', 'PLOTTER');
create type public.colormode as enum ('C4_0', 'C4_4');
create type public.unit as enum ('SHEET', 'SQM', 'PER_1000', 'JOB', 'PER_ITEM');

create table public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text not null unique,
  role public.userrole not null default 'VENDEDOR',
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz,
  deleted_at timestamptz
);

create table public.legacy_user_migrations (
  legacy_user_id bigint primary key,
  user_id uuid not null unique references public.users(id) on delete cascade,
  migrated_at timestamptz not null default timezone('utc', now())
);

create or replace function public.create_auth_profile()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.users (id, name, email)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'name', new.email), new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger auth_user_profile
after insert on auth.users
for each row execute procedure public.create_auth_profile();

